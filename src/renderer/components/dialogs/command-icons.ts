/** The glyph for a palette row: the command's own, else its category's. */
export function commandIcon(item: Pick<CommandMenuItem, "name" | "category">): LucideIcon {
	// A plugin may register a command named like an Object.prototype member.
	return (
		(Object.hasOwn(COMMAND_ICONS, item.name) ? COMMAND_ICONS[item.name] : undefined) ??
		CATEGORY_ICONS[item.category] ??
		Slash
	);
}
